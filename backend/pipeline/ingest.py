"""
ingest.py — End-to-end document ingestion orchestrator.

This module is the single entry point for the ingestion pipeline.
It coordinates doc_processor → chunker → embedder and updates SQLite
throughout so the UI can track progress via the /status endpoint.

Call run_ingestion() from a FastAPI background task — it is synchronous
and may take 10–60 seconds depending on document size.
"""

from __future__ import annotations

import logging
from pathlib import Path

from backend.database import sqlite_db
from backend.pipeline.doc_processor import process_pdf
from backend.pipeline.chunker import chunk_document
from backend.pipeline.embedder import embed_and_store
from backend.database.vector_db import delete_document_chunks

logger = logging.getLogger(__name__)


def run_ingestion(doc_id: str, file_path: Path, filename: str) -> None:
    """
    Full ingestion pipeline for one PDF document.

    Steps:
        1. Parse PDF → list of PageContent objects
        2. Chunk pages → list of Chunk objects (with page/section metadata)
        3. Embed chunks → vectors stored in ChromaDB
        4. Update SQLite document record with final counts and status

    On any failure, the document record is updated to status='error' and
    the partially written ChromaDB entries are cleaned up.

    Parameters
    ----------
    doc_id    : Unique identifier for this document (generated by the router).
    file_path : Absolute path to the saved PDF on disk.
    filename  : Original filename (for display and metadata).
    """
    logger.info("[%s] Ingestion started for '%s'", doc_id, filename)

    try:
        # ── Step 1: Parse PDF ──────────────────────────────────────────────
        logger.info("[%s] Step 1/3 — Parsing PDF …", doc_id)
        doc_content = process_pdf(file_path)

        non_empty = len(doc_content.non_empty_pages)
        logger.info(
            "[%s] Parsed %d pages (%d with content).",
            doc_id,
            doc_content.total_pages,
            non_empty,
        )

        if non_empty == 0:
            raise ValueError(
                "No readable text was found in this PDF. "
                "It may be a scanned image-only document."
            )

        # ── Step 2: Chunk ──────────────────────────────────────────────────
        logger.info("[%s] Step 2/3 — Chunking …", doc_id)
        chunks = chunk_document(doc_content, doc_id)

        if not chunks:
            raise ValueError("Chunking produced zero chunks. The document may be empty.")

        logger.info("[%s] Produced %d chunks.", doc_id, len(chunks))

        # ── Step 3: Embed and store ────────────────────────────────────────
        logger.info("[%s] Step 3/3 — Embedding and storing in ChromaDB …", doc_id)
        stored = embed_and_store(chunks)

        # ── Update SQLite record ───────────────────────────────────────────
        sqlite_db.update_document_ready(
            doc_id      = doc_id,
            page_count  = doc_content.total_pages,
            chunk_count = stored,
        )

        logger.info(
            "[%s] Ingestion complete. Pages: %d | Chunks: %d",
            doc_id,
            doc_content.total_pages,
            stored,
        )

    except Exception as exc:
        error_msg = str(exc)
        logger.error("[%s] Ingestion failed: %s", doc_id, error_msg)

        # Clean up any partial ChromaDB writes
        try:
            delete_document_chunks(doc_id)
        except Exception as cleanup_exc:
            logger.warning("[%s] ChromaDB cleanup failed: %s", doc_id, cleanup_exc)

        sqlite_db.update_document_error(doc_id, error_msg)
